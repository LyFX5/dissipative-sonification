def _value_to_rgb(v):
    """Map a float in [0,1] to a 3x? RGB image via the inferno LUT."""
    idx = (np.clip(v, 0.0, 1.0) * (len(_INFERNO) - 1)).astype(np.int32)
    return _INFERNO[idx]


class MatrixWidget(QWidget):
    def __init__(self, sim: GrayScott, parent=None):
        super().__init__(parent)
        self.sim = sim
        self.setMinimumSize(320, 320)
        self._image = None
        self._painting = False
        self._last_pos = None
        self.setMouseTracking(True)

    # ------------------------------------------------------------------ #
    # Rendering
    # ------------------------------------------------------------------ #
    def _rebuild_image(self):
        rgb = _value_to_rgb(self.sim.V)
        rgb8 = (rgb * 255.0).astype(np.uint8)
        h, w = rgb8.shape[:2]
        img = QImage(rgb8.data, w, h, w * 3, QImage.Format_RGB888)
        self._image = img.copy()

    def update_frame(self):
        self._rebuild_image()
        self.update()

    def paintEvent(self, event):
        painter = QPainter(self)
        painter.fillRect(self.rect(), QColor(10, 10, 12))
        if self._image is None:
            self._rebuild_image()
        scaled = self._image.scaled(
            self.size(), Qt.KeepAspectRatio, Qt.FastTransformation
        )
        x = (self.width() - scaled.width()) // 2
        y = (self.height() - scaled.height()) // 2
        painter.drawImage(x, y, scaled)

    # ------------------------------------------------------------------ #
    # Interaction: click / scrub to inject concentration
    # ------------------------------------------------------------------ #
    def _event_to_grid(self, pos) -> tuple | None:
        if self._image is None:
            return None
        # recompute the same placement as paintEvent
        scaled = self._image.scaled(
            self.size(), Qt.KeepAspectRatio, Qt.FastTransformation
        )
        x = (self.width() - scaled.width()) // 2
        y = (self.height() - scaled.height()) // 2
        if not (
            x <= pos.x() < x + scaled.width()
            and y <= pos.y() < y + scaled.height()
        ):
            return None
        gx = (pos.x() - x) / scaled.width() * self.sim.width
        gy = (pos.y() - y) / scaled.height() * self.sim.height
        return gx, gy

    def _paint_at(self, pos):
        grid = self._event_to_grid(pos)
        if grid is not None:
            self.sim.add_brush(*grid)

    def mousePressEvent(self, event):
        if event.button() == Qt.LeftButton:
            self._painting = True
            self._paint_at(event.position())
            self.update()
        elif event.button() == Qt.RightButton:
            self.sim.reset()

    def mouseMoveEvent(self, event):
        if self._painting:
            pos = event.position()
            self._paint_at(pos)
            self._last_pos = pos
            self.update()

    def mouseReleaseEvent(self, event):
        if event.button() == Qt.LeftButton:
            self._painting = False
            self._last_pos = None
